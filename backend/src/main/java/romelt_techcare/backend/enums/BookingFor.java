package romelt_techcare.backend.enums;

/**
 * ================================================================
 * ROMELT TECHCARE — BOOKING FOR
 * ================================================================
 *
 * Purpose:
 * Identifies whether a service request is for the customer's
 * personal use or for a business represented by the customer.
 *
 * Values:
 * - PERSONAL: The service is requested for the individual customer.
 * - BUSINESS: The customer is the contact person requesting service
 *   on behalf of a business.
 * ================================================================
 */
public enum BookingFor {

    PERSONAL,

    BUSINESS
}